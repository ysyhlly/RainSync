// Owned fixed-version REST and short media decode checks. This is deliberately
// separate from the RainSync browser/lifecycle matrix, which remains required.
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { isolatedUpstreamReal } from "./fixtures/upstream-real.mjs";

const execute = promisify(execFile);
const entry = fileURLToPath(import.meta.url);
const runId = randomUUID();
const root = resolve(
  process.env.RAINSYNC_RUNTIME_ROOT ?? ".runtime",
  "upstream-real-contracts",
  runId,
);
const ffmpegBin = process.env.RAINSYNC_FFMPEG_BIN;
const selection = process.argv[2] ?? "all";
assert.ok(["all", "jellyfin", "emby"].includes(selection));
assert.equal(process.argv.length <= 3, true);
const kinds = selection === "all" ? ["jellyfin", "emby"] : [selection];
await mkdir(root, { recursive: true });
const digest = async (path) =>
  createHash("sha256")
    .update(await readFile(path))
    .digest("hex");
const report = {
  run_id: runId,
  started_at: new Date().toISOString(),
  source_sha256: await digest(entry),
  source_commit: (
    await execute("git", ["rev-parse", "HEAD"], {
      cwd: dirname(dirname(entry)),
      encoding: "utf8",
    })
  ).stdout.trim(),
  result: "running",
  scope:
    "Fixed isolated real products: browsing, PlaybackInfo, media decode, HLS seeks on the returned manifest timeline, audio selection, check-ins, independent devices and upstream media-policy revocation. No RainSync production adapter/browser/authentication integration or soak claim.",
  products: [],
  unverified: [
    "RainSync public adapter dispatch",
    "RainSync reservation/observation/cleanup integration",
    "Browser audio/subtitle rendering",
    "RainSync single-login revocation",
    "Long-lived stream revocation window",
    "Other product versions",
  ],
};
const reportPath = resolve(root, "report.json");
const save = () =>
  writeFile(reportPath, JSON.stringify(report, null, 2) + "\n");
const delay = (ms) => new Promise((done) => setTimeout(done, ms));
async function until(check, label) {
  const end = Date.now() + 15000;
  while (Date.now() < end) {
    const value = await check();
    if (value) return value;
    await delay(100);
  }
  throw new Error(`deadline: ${label}`);
}
function profile(userId, { position = 0, audio = null, direct = false, mediaSourceId = null } = {}) {
  return {
    UserId: userId,
    IsPlayback: true,
    AutoOpenLiveStream: false,
    StartTimeTicks: Math.round(position * 10000),
    AudioStreamIndex: audio,
    MediaSourceId: mediaSourceId,
    SubtitleStreamIndex: -1,
    EnableDirectPlay: direct,
    EnableDirectStream: !direct,
    EnableTranscoding: !direct,
    AllowVideoStreamCopy: false,
    DeviceProfile: {
      Name: "RainSync Web",
      MaxStreamingBitrate: 12000000,
      SubtitleProfiles: [{ Format: "vtt", Method: "External" }],
      DirectPlayProfiles: direct
        ? [
            {
              Container: "mp4",
              Type: "Video",
              VideoCodec: "h264",
              AudioCodec: "aac",
            },
          ]
        : [],
      TranscodingProfiles: direct
        ? []
        : [
            {
              Container: "ts",
              Type: "Video",
              Protocol: "hls",
              VideoCodec: "h264",
              AudioCodec: "aac",
              Context: "Streaming",
              MaxAudioChannels: "2",
            },
          ],
    },
  };
}

for (const kind of kinds) {
  const product = { kind, result: "running", cases: [], reservations: [] };
  report.products.push(product);
  await save();
  try {
    const result = await isolatedUpstreamReal(
      kind,
      async (upstream) => {
        product.image = upstream.metadata.image;
        product.image_id = upstream.metadata.image_id;
        product.version = upstream.metadata.actual_version;
        product.samples = upstream.metadata.samples;
        product.ffmpeg = upstream.metadata.ffmpeg;
        const ffmpeg = product.ffmpeg.find(
          (tool) => tool.tool === "ffmpeg",
        ).path;
        const ffprobe = product.ffmpeg.find(
          (tool) => tool.tool === "ffprobe",
        ).path;
        // Browse DTOs need not include MediaStreams. These names identify only the
        // two synthetic files generated by this fixture; decode verifies codecs.
        const h264 = upstream.items.find(
          (item) => item.Name === "rainsync-h264",
        );
        const hevc = upstream.items.find(
          (item) => item.Name === "rainsync-hevc",
        );
        assert.ok(h264 && hevc);
        const clientA = await upstream.client({
          deviceId: `rainsync-a-${runId}`,
          restricted: true,
        });
        const clientB = await upstream.client({
          deviceId: `rainsync-b-${runId}`,
          restricted: true,
        });
        // Same dedicated account, distinct device IDs. The fixture's admin is
        // dedicated to this disposable product, and contains no personal history.
        const sameAccountB = await upstream.client(`rainsync-same-${runId}`);
        const base = new URL(upstream.base + "/");
        const ownedPath = (value, relativeTo = base) => {
          // Emby's PlaybackInfo may return /Videos/... relative to the configured
          // /emby base. Preserve that base exactly like providers::upstream_url.
          const path =
            typeof value === "string" &&
            value.startsWith("/") &&
            !value.startsWith("//") &&
            !value.startsWith(base.pathname)
              ? value.slice(1)
              : value;
          const url = new URL(path, relativeTo);
          assert.equal(
            url.origin,
            base.origin,
            "Only this owned upstream origin may receive its credentials",
          );
          assert.ok(url.pathname.startsWith(base.pathname));
          return {
            url,
            path: "/" + url.pathname.slice(base.pathname.length) + url.search,
          };
        };
        const read = async (
          client,
          value,
          relativeTo,
          limit = 8 * 1024 * 1024,
        ) => {
          const { url, path } = ownedPath(value, relativeTo);
          const response = await client.raw(path, { timeout: 15000 });
          assert.equal(response.status, 200, "Owned media resource succeeds");
          const chunks = [];
          let length = 0;
          try {
            for await (const chunk of response.body) {
              length += chunk.byteLength;
              assert.ok(
                length <= limit,
                "Owned media resource has a byte limit",
              );
              chunks.push(Buffer.from(chunk));
            }
          } catch (error) {
            await response.body?.cancel().catch(() => {});
            throw error;
          }
          return { url, bytes: Buffer.concat(chunks) };
        };
        const caseRun = async (name, action) => {
          const row = { name, result: "running" };
          product.cases.push(row);
          await save();
          try {
            await action(row);
            row.result = "passed";
          } catch (error) {
            row.result = "failed";
            row.error = error.message;
            product.result = "failed";
            process.exitCode = 1;
          }
          await save();
          console.log(
            `${row.result === "passed" ? "PASS" : "FAIL"} ${kind}: ${name}`,
          );
        };
        const active = [];
        const negotiate = async (client, item, options) => {
          const info = await client.api(
            `/Items/${item.Id}/PlaybackInfo`,
            "POST",
            profile(client.userId, options),
          );
          assert.ok(info.PlaySessionId && info.MediaSources?.length);
          const source = info.MediaSources[0];
          const grant = {
            client,
            item,
            sid: info.PlaySessionId,
            source,
            position: options?.position ?? 0,
          };
          // Register immediately, before validating or fetching the selected route.
          active.push(grant);
          product.reservations.push({
            sid: grant.sid,
            device_id: client.deviceId,
            user_id: client.userId,
            item_id: item.Id,
            position_ms: grant.position,
            audio_index: options?.audio ?? null,
          });
          return grant;
        };
        const body = (grant, position = grant.position) => ({
          ItemId: grant.item.Id,
          MediaSourceId: grant.source.Id,
          PlaySessionId: grant.sid,
          PositionTicks: Math.round(position * 10000),
          CanSeek: true,
          IsPaused: false,
          PlayMethod: grant.source.TranscodingUrl ? "Transcode" : "DirectPlay",
        });
        const stop = async (grant) => {
          if (grant.stopped) return;
          await grant.client.api(
            "/Sessions/Playing/Stopped",
            "POST",
            body(grant),
          );
          if (kind === "emby")
            await grant.client.api(
              `/Videos/ActiveEncodings?DeviceId=${encodeURIComponent(grant.client.deviceId)}&PlaySessionId=${encodeURIComponent(grant.sid)}`,
              "DELETE",
              undefined,
              [200, 204],
            );
          grant.stopped = true;
        };
        const decode = async (
          bytes,
          name,
          expectedPosition,
          seekMs = 0,
          audioHz = null,
        ) => {
          const path = resolve(root, `${kind}-${name}.media`);
          await writeFile(path, bytes);
          const { stdout: probe } = await execute(
            ffprobe,
            ["-v", "error", "-show_streams", "-show_format", "-of", "json", path],
            { encoding: "utf8", timeout: 15000 },
          );
          const probed = JSON.parse(probe);
          const diagnostic = {
            name,
            byte_length: bytes.length,
            sha256: await digest(path),
            expected_position_ms: expectedPosition,
            seek_in_window_ms: seekMs,
            format_start_time: probed.format?.start_time ?? null,
            format_duration: probed.format?.duration ?? null,
            streams: probed.streams.map(({ index, codec_name, codec_type, width, height, start_time, duration }) =>
              ({ index, codec_name, codec_type, width, height, start_time, duration })),
          };
          (product.decode_attempts ??= []).push(diagnostic);
          const { stdout } = await execute(
            ffmpeg,
            [
              "-v",
              "error",
              "-nostdin",
              "-threads",
              "1",
              "-i",
              path,
              "-ss",
              String(seekMs / 1000),
              "-frames:v",
              "1",
              "-pix_fmt",
              "gray",
              "-threads",
              "1",
              "-f",
              "rawvideo",
              "pipe:1",
            ],
            { encoding: "buffer", timeout: 15000, maxBuffer: 1024 * 1024 },
          );
          const video = probed.streams.find(
            (stream) => stream.codec_type === "video",
          );
          assert.ok(video && stdout.length >= video.width * video.height);
          let frame = 0;
          for (let bit = 0; bit < 16; bit++) {
            const x = Math.round(((bit * 8 + 4) * video.width) / 320);
            const y = Math.round((6 * video.height) / 180);
            if (stdout[y * video.width + x] > 128) frame += 2 ** bit;
          }
          const decodedPosition = frame * 100;
          assert.ok(
            Math.abs(decodedPosition - expectedPosition) <= 600,
            "Decoded source pixels match the requested seek position within 600 ms",
          );
          let measuredHz;
          if (audioHz !== null) {
            const { stdout: pcm } = await execute(
              ffmpeg,
              [
                "-v",
                "error",
                "-nostdin",
                "-threads",
                "1",
                "-i",
                path,
                "-ss",
                String(seekMs / 1000),
                "-t",
                "0.3",
                "-vn",
                "-ac",
                "1",
                "-ar",
                "8000",
                "-f",
                "f32le",
                "pipe:1",
              ],
              { encoding: "buffer", timeout: 15000, maxBuffer: 1024 * 1024 },
            );
            let crossings = 0;
            const samples = pcm.length / 4;
            assert.ok(samples >= 800);
            for (let index = 1; index < samples; index++)
              if (
                pcm.readFloatLE((index - 1) * 4) <= 0 &&
                pcm.readFloatLE(index * 4) > 0
              )
                crossings++;
            measuredHz = (crossings * 8000) / samples;
            assert.ok(
              Math.abs(measuredHz - audioHz) < 30,
              "Decoded audio belongs to the selected synthetic source track",
            );
          }
          return {
            sha256: await digest(path),
            byte_length: bytes.length,
            video_codec: video.codec_name,
            decoded_source_position_ms: decodedPosition,
            requested_position_ms: expectedPosition,
            expected_audio_hz: audioHz,
            measured_audio_hz: measuredHz,
          };
        };
        const firstHls = async (grant, name, audioHz = null) => {
          assert.ok(grant.source.TranscodingUrl, "Real product selected HLS");
          let manifest = await read(
            grant.client,
            grant.source.TranscodingUrl,
            base,
            256 * 1024,
          );
          let lines;
          for (let depth = 0; depth <= 2; depth++) {
            const text = manifest.bytes.toString("utf8");
            assert.ok(text.startsWith("#EXTM3U"));
            lines = text.split(/\r?\n/).map((line) => line.trim());
            if (!lines.some((line) => line.startsWith("#EXT-X-STREAM-INF")))
              break;
            const resource = lines.find(
              (line) => line && !line.startsWith("#"),
            );
            assert.ok(resource && depth < 2, "Bounded master traversal");
            manifest = await read(
              grant.client,
              resource,
              manifest.url,
              256 * 1024,
            );
          }
          assert.equal(lines.includes("#EXT-X-DISCONTINUITY"), false, "Owned VOD window has one continuous timeline");
          assert.equal(lines.some((line) => line.startsWith("#EXT-X-BYTERANGE:")), false, "Owned fixture uses complete TS/fMP4 segments");
          let start = 0, pendingDuration = null;
          const segments = [];
          for (const line of lines) {
            if (line.startsWith("#EXTINF:")) {
              pendingDuration = Number(line.slice(8).split(",")[0]) * 1000;
              assert.ok(
                Number.isFinite(pendingDuration) && pendingDuration > 0,
              );
            } else if (line && !line.startsWith("#")) {
              assert.ok(pendingDuration !== null);
              segments.push({ uri: line, start, duration: pendingDuration });
              start += pendingDuration;
              pendingDuration = null;
            }
          }
          const selected = segments.findIndex((segment) => grant.position < segment.start + segment.duration);
          assert.ok(selected >= 0, "Real HLS covers the requested timestamp");
          // Decode the returned HLS timeline, including bounded adjacent data for
          // decoder initialization and segment-boundary samples. A lone TS file
          // is not the same input as the contiguous HLS stream a player consumes.
          const window = segments.slice(Math.max(0, selected - 1), selected + 2);
          const segmentStart = segments[selected].start;
          const windowStart = window[0].start;
          const diagnostic = { name, requested_position_ms: grant.position,
            selected_segment_start_ms: segmentStart, window_start_ms: windowStart,
            media_sequence: lines.find((line) => line.startsWith("#EXT-X-MEDIA-SEQUENCE:")) ?? null,
            segments: [] };
          (product.hls_windows ??= []).push(diagnostic);
          const init = /URI="([^"]+)"/.exec(
            lines.find((line) => line.startsWith("#EXT-X-MAP:")) ?? "",
          )?.[1];
          const chunks = init ? [(await read(grant.client, init, manifest.url, 1024 * 1024)).bytes] : [];
          for (const segment of window) {
            const media = await read(grant.client, segment.uri, manifest.url);
            chunks.push(media.bytes);
            diagnostic.segments.push({ start_ms: segment.start, duration_ms: segment.duration,
              byte_length: media.bytes.length, sha256: createHash("sha256").update(media.bytes).digest("hex") });
          }
          const bytes = Buffer.concat(chunks);
          assert.ok(bytes.length <= 25 * 1024 * 1024, "At most three bounded segments and one initialization section");
          return {
            segment_start_ms: segmentStart,
            ...(await decode(
              bytes,
              name,
              grant.position,
              grant.position - windowStart,
              audioHz,
            )),
          };
        };
        try {
          await caseRun(
            "real browse permissions and fixed-version setup",
            async (row) => {
              const page = await clientA.api(
                `/Users/${clientA.userId}/Items?Recursive=true&IncludeItemTypes=Movie,Episode,Video&Limit=1&StartIndex=0&EnableTotalRecordCount=true`,
              );
              assert.equal(page.TotalRecordCount, 2);
              assert.equal(page.Items.length, 1);
              row.sample_count = upstream.items.length;
              row.anonymous_status = upstream.metadata.anonymous_status;
            },
          );
          await caseRun(
            "direct H264 negotiation and real output decode",
            async (row) => {
              const grant = await negotiate(clientA, h264, { direct: true });
              assert.equal(grant.source.SupportsDirectPlay, true);
              const url = new URL(`Videos/${h264.Id}/stream.mp4`, base);
              url.searchParams.set("Static", "true");
              url.searchParams.set("MediaSourceId", grant.source.Id);
              url.searchParams.set("PlaySessionId", grant.sid);
              url.searchParams.set("DeviceId", clientA.deviceId);
              row.output = await decode(
                (await read(clientA, url, base)).bytes,
                "direct",
                0,
              );
              await clientA.api("/Sessions/Playing", "POST", body(grant));
              await stop(grant);
            },
          );
          await caseRun(
            "three real HLS seeks and decoded selected audio tracks",
            async (row) => {
              row.outputs = [];
              const seed = await negotiate(clientA, hevc, { position: 0 });
              const tracks = seed.source.MediaStreams.filter(
                (stream) => stream.Type === "Audio",
              );
              await stop(seed);
              assert.equal(tracks.length, 2);
              for (const [index, position] of [
                10_000, 27_000, 43_000,
              ].entries()) {
                const audio = tracks[index % tracks.length].Index;
                const grant = await negotiate(clientA, hevc, {
                  position,
                  audio,
                  // Both products bind a requested stream index to its actual
                  // media source. This ID is observed, never derived from item ID.
                  mediaSourceId: seed.source.Id,
                });
                assert.equal(
                  grant.source.DefaultAudioStreamIndex,
                  audio,
                  "Real selected audio stream index",
                );
                row.outputs.push({
                  audio_index: audio,
                  ...(await firstHls(
                    grant,
                    `seek-${index}`,
                    index % tracks.length === 0 ? 440 : 880,
                  )),
                });
                await clientA.api("/Sessions/Playing", "POST", body(grant));
                await clientA.api("/Sessions/Playing/Progress", "POST", {
                  ...body(grant, position + 500),
                  EventName: "Pause",
                  IsPaused: true,
                });
                await stop(grant);
              }
            },
          );
          await caseRun(
            "same account distinct devices; stopping A preserves B media and progress",
            async (row) => {
              const a = await negotiate(upstream.admin, hevc, { position: 0 });
              const b = await negotiate(sameAccountB, hevc, { position: 0 });
              assert.equal(a.client.userId, b.client.userId);
              assert.notEqual(a.client.deviceId, b.client.deviceId);
              assert.notEqual(a.sid, b.sid);
              row.before_a = await firstHls(a, "same-a");
              row.before_b = await firstHls(b, "same-b");
              await a.client.api("/Sessions/Playing", "POST", body(a));
              await b.client.api("/Sessions/Playing", "POST", body(b));
              await stop(a);
              const sessions = await until(async () => {
                const values = await upstream.admin.api("/Sessions");
                return values.some(
                  (session) =>
                    session.DeviceId === b.client.deviceId &&
                    session.NowPlayingItem?.Id === hevc.Id,
                )
                  ? values
                  : null;
              }, "B remains independently active after A Stop");
              b.position = 3000;
              row.after_b = await firstHls(b, "same-b-after-stop-a");
              assert.ok(
                row.after_b.decoded_source_position_ms >
                  row.before_b.decoded_source_position_ms,
                "After stopping A, B's independently authorized media continues at a later decoded source frame",
              );
              await b.client.api("/Sessions/Playing/Progress", "POST", body(b));
              row.surviving_device = b.client.deviceId;
              row.visible_session_count = sessions.length;
              await stop(b);
            },
          );
          await caseRun(
            "real upstream media-policy revocation does not revoke another account",
            async (row) => {
              const grant = await negotiate(clientA, h264, { direct: true });
              row.policy_change = await upstream.revokeClient(clientA);
              const denied = await clientA.raw(
                `/Items/${h264.Id}/PlaybackInfo`,
                {
                  method: "POST",
                  body: profile(clientA.userId, { direct: true }),
                },
              );
              const result = denied.status === 200 ? await denied.json() : null;
              row.playback_info_status = denied.status;
              row.playback_info_code = result?.ErrorCode ?? null;
              row.playback_info_direct =
                result?.MediaSources?.[0]?.SupportsDirectPlay ?? null;
              const resource = new URL(`Videos/${h264.Id}/stream.mp4`, base);
              resource.searchParams.set("Static", "true");
              resource.searchParams.set("MediaSourceId", grant.source.Id);
              resource.searchParams.set("PlaySessionId", grant.sid);
              resource.searchParams.set("DeviceId", clientA.deviceId);
              const deniedMedia = await clientA.raw(ownedPath(resource).path);
              row.media_status = deniedMedia.status;
              await deniedMedia.body?.cancel();
              row.media_status_samples = [{ after_ms: 0, status: deniedMedia.status }];
              const firstSampleAt = Date.now();
              for (const waitMs of [1000, 2000]) {
                await delay(waitMs);
                const sample = await clientA.raw(ownedPath(resource).path);
                row.media_status_samples.push({ after_ms: Date.now() - firstSampleAt, status: sample.status });
                await sample.body?.cancel();
              }
              // Measure the unrelated account even when A's product permission
              // semantics fail the denial assertion. Do not replace media-policy
              // revocation with account disablement or logout to make it green.
              const other = await negotiate(clientB, h264, { direct: true });
              assert.equal(other.source.SupportsDirectPlay, true);
              const otherResource = new URL(`Videos/${h264.Id}/stream.mp4`, base);
              otherResource.searchParams.set("Static", "true");
              otherResource.searchParams.set("MediaSourceId", other.source.Id);
              otherResource.searchParams.set("PlaySessionId", other.sid);
              otherResource.searchParams.set("DeviceId", clientB.deviceId);
              row.other_account_output = await decode(
                (await read(clientB, otherResource, base)).bytes,
                "other-account-after-media-policy-revocation", 0,
              );
              await stop(grant);
              await stop(other);
              assert.ok(
                [401, 403].includes(deniedMedia.status),
                "Revoked policy denies actual media access, even when PlaybackInfo still returns metadata",
              );
            },
          );
        } finally {
          product.stop_cleanup = [];
          for (const grant of active) {
            try {
              await stop(grant);
              product.stop_cleanup.push({ sid: grant.sid, stopped: true });
            } catch {
              product.stop_cleanup.push({ sid: grant.sid, stopped: false });
            }
          }
        }
      },
      {
        artifactRoot: resolve(root, kind, "fixture"),
        ffmpegBin,
        durationSeconds: 60,
      },
    );
    product.setup_report_path = result.reportPath;
    product.cleanup = result.metadata.cleanup;
    if (product.result !== "failed") product.result = "passed";
  } catch (error) {
    product.result = "failed";
    product.error = error.message;
    if (error.cause) product.cause = error.cause.message;
    process.exitCode = 1;
  }
  await save();
}
report.result = report.products.every((product) => product.result === "passed")
  ? "passed"
  : "failed";
report.finished_at = new Date().toISOString();
assert.equal(
  await digest(entry),
  report.source_sha256,
  "Entry stayed frozen through both product runs",
);
await save();
console.log(reportPath);
