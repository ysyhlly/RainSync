  check('only accessible live sources are counted',[root.entries.length,root.total_media],[1,62]);
  check('HTTP browse is private and uncacheable',(await viewer.raw('/media/browse')).headers.get('cache-control'),'no-store');
  const sharedNode=root.entries[0].id;
  let page=await browse(viewer,sharedNode);
  check('source has one real folder and one direct media card',page.entries.map(e=>e.type),['folder','media']);
  check('descendant count is complete beyond one media page',page.entries[0].media_count,61);
  const shows=page.entries[0].id;
  page=await browse(viewer,shows); const series=page.entries[0].id;
  page=await browse(viewer,series); const season=page.entries[0].id;
  page=await browse(viewer,season);
  check('breadcrumbs include every real ancestor',page.breadcrumbs.map(b=>b.name),['全部片源','Nested source','Shows','Series','Season 1']);
  const first=page; const second=await browse(viewer,season,page.next_cursor); const third=await browse(viewer,season,second.next_cursor);
  check('bounded stable media pages',[first.entries.length,second.entries.length,third.entries.length],[24,24,13]);
  check('no duplicate children across pages',new Set([...first.entries,...second.entries,...third.entries].map(e=>e.media.id)).size,61);
  check('cross-directory cursor has a normalized error',(await browse(viewer,sharedNode,first.next_cursor,undefined,400)).error.code,'INVALID_REQUEST');
  checks.push('cursor cannot be replayed at another directory');
  check('malformed node has a normalized error',(await viewer.request('/media/browse?node=invalid','GET',undefined,400)).error.code,'INVALID_REQUEST');
