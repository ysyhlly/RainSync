  await browse(viewer,hostile,undefined,undefined,400);
  const missing=Buffer.from(JSON.stringify({version:1,source:shared,path:['no-such-folder']})).toString('base64url');
  check('missing folder has a normalized error',(await browse(viewer,missing,undefined,undefined,404)).error.code,'MEDIA_NOT_FOUND');
  check('legacy cross-directory title search remains available',(await viewer.request('/media?search=Loose')).length,1);
