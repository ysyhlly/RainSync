  await browse(viewer,season,undefined,undefined,404);
  f.sql(`UPDATE private_libraries SET deleted_at=clock_timestamp() WHERE id='${library}'`);
  await browse(owner,privateNode,undefined,library,404);
  checks.push('source and library tombstones fence existing directory navigation');
